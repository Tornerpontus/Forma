// Captures phone-sized screenshots of key screens (local dev data). Usage: node scripts/screenshots.mjs <outdir>
import { chromium } from '@playwright/test'
const out = process.argv[2] ?? 'screenshots'
const base = process.env.BASE ?? 'http://127.0.0.1:4173'
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'sv-SE' })
const page = await ctx.newPage()
const shot = async (name, full = false) => {
  await page.waitForTimeout(700)
  await page.screenshot({ path: `${out}/${name}.png`, fullPage: full })
}
await page.goto(`${base}/login`)
await shot('01-login')
await page.getByLabel('E-post').fill('demo@forma.test')
await page.getByLabel('Lösenord').fill('demo-password')
await page.getByRole('button', { name: 'Logga in' }).click()
await page.getByRole('heading', { name: 'Dags att träna?' }).waitFor()
await shot('02-home', true)
await page.goto(`${base}/history`)
await shot('03-history')
await page.getByTestId('history-item').first().click()
await page.getByTestId('workout-title').waitFor()
await shot('04-workout-detail', true)
await page.goto(`${base}/progress`)
await page.getByTestId('strength-chart').waitFor()
await shot('05-progress', true)
await page.goto(`${base}/exercises`)
await shot('06-exercises')
await page.getByLabel('Sök övning').fill('Bänkpress')
await page.getByRole('link', { name: /^Bänkpress/ }).first().click()
await page.getByText('Personliga rekord').waitFor()
await shot('07-exercise-detail', true)
await page.goto(`${base}/programs`)
await shot('08-programs')
await page.goto(`${base}/`)
await page.getByTestId('start-empty').click()
await page.getByRole('button', { name: 'Lägg till övning' }).first().click()
await page.waitForTimeout(400)
await shot('09-picker')
await page.getByLabel('Sök övning').fill('Bänkpress')
await page.getByRole('button', { name: /^Bänkpress/ }).first().click()
await page.getByLabel('Sök övning').fill('Lutande hantelpress')
await page.getByRole('button', { name: /^Lutande hantelpress/ }).first().click()
await page.getByRole('button', { name: /Lägg till 2 övningar/ }).click()
const b = page.getByTestId('exercise-block').first()
await b.getByRole('button', { name: 'Markera set 1 som klart' }).click()
await b.getByLabel('Vikt set 2').fill('80')
await shot('10-active-workout')
await page.goto(`${base}/settings`)
await shot('11-settings')
// clean up the active workout
await page.goto(`${base}/workout`)
await page.getByRole('button', { name: 'Avbryt och radera passet' }).click()
await page.getByRole('button', { name: 'Radera' }).click()
await browser.close()
console.log('done')
